void analyze_packet(uint8_t *data, size_t data_len) {
    printf("Analyzing H.225 packet structure...\n");
    printf("Total length: %zu bytes\n\n", data_len);
    
    // The first few bytes might be Q.931 header, H.225 UserInformation is typically 
    // embedded in the Q.931 User-user information element
    
    printf("First 64 bytes with interpretation:\n");
    for (int i = 0; i < 64 && i < data_len; i++) {
        printf("%02x ", data[i]);
        if ((i + 1) % 16 == 0) {
            printf("  |  ");
            for (int j = i - 15; j <= i; j++) {
                printf("%c", (data[j] >= 32 && data[j] <= 126) ? data[j] : '.');
            }
            printf("\n");
        }
    }
    printf("\n");
    
    // Look for Q.931-like patterns
    if (data[0] == 0x08 || data[0] == 0x60) {
        printf("First byte 0x%02x suggests this might be Q.931/H.225 call signaling\n", data[0]);
    }
    
    // Look for potential User-user information element (0x7E)
    printf("\nSearching for User-user information element (0x7E):\n");
    for (int i = 0; i < data_len - 1; i++) {
        if (data[i] == 0x7E) {
            printf("Found 0x7E at offset %d, next byte: 0x%02x\n", i, data[i+1]);
            if (i + 2 < data_len) {
                printf("Following bytes: ");
                for (int j = i; j < i + 16 && j < data_len; j++) {
                    printf("%02x ", data[j]);
                }
                printf("\n");
            }
        }
    }
    
    // Let's also look for the H.225 protocol discriminator
    printf("\nSearching for H.225 protocol patterns:\n");
    
    // H.225 UserInformation often starts with a specific pattern
    // Look for potential starts of H.225 data
    for (int i = 0; i < data_len - 8; i++) {
        // Look for sequence start patterns
        if ((data[i] == 0x30 && data[i+1] > 0x80) ||  // Long form length
            (data[i] == 0x60 && data[i+1] > 0x80)) {   // H225-UU-PDU typically starts with 0x60
            printf("Potential ASN.1 SEQUENCE at offset %d: ", i);
            for (int j = i; j < i + 8 && j < data_len; j++) {
                printf("%02x ", data[j]);
            }
            printf("\n");
        }
    }
    
    // Looking specifically for Setup-UUIE patterns
    printf("\nLooking for Setup-UUIE specific patterns...\n");
    
    // Protocol identifier for H.225.0 is typically { 0 0 8 2250 0 version }
    // This translates to OID encoding
    for (int i = 0; i < data_len - 10; i++) {
        if (data[i] == 0x06 && data[i+1] >= 0x08 && data[i+1] <= 0x0C) {  // OID tag and reasonable length
            printf("Potential Protocol Identifier OID at offset %d: ", i);
            int oid_len = data[i+1];
            for (int j = i; j < i + 2 + oid_len && j < data_len; j++) {
                printf("%02x ", data[j]);
            }
            printf("\n");
        }
    }
}

